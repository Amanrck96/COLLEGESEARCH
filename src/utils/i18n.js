export const useTranslation = () => {
  const t = useCallback((key, defaultValueOrOptions, options) => {
    if (key === '__proto__' || key === 'constructor' || key === 'prototype') {
      return typeof defaultValueOrOptions === 'string' ? defaultValueOrOptions : key;
    }

    let text = Reflect.get(translations, key);
    let defaultValue = typeof defaultValueOrOptions === 'string' ? defaultValueOrOptions : undefined;
    let vars = typeof defaultValueOrOptions === 'object' ? defaultValueOrOptions : options;

    if (text === undefined) {
      text = defaultValue !== undefined ? defaultValue : key;
    }

    if (vars) {
      Object.keys(vars).forEach(k => {
        text = text.replace(new RegExp(`{${k}}`, 'g'), vars[k]);
      });
    }

    return text;
  }, []);

  return { t };
};

